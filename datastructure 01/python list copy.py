a = [1, 2, 3]
b = a
b.append(5)
print('a: ', a)
print('b: ', b)
'''
실행결과
a:  [1, 2, 3, 5]
b:  [1, 2, 3, 5]
'''

a = [1, 2, 3]
b = a[:]
b.append(5)
print('a: ', a)
print('b: ', b)
'''
실행결과
a:  [1, 2, 3]
b:  [1, 2, 3, 5]
'''

a = [[1, 2], [3, 4]]
